"""Markdown health report generation."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from forgefix import __version__
from forgefix.core.scanner import ScanResult
from forgefix.core.score import ScoreResult

# Status labels for tables and reports. (bandit flags dict keys as passwords: false positive.)
STATUS_LABEL = {"pass": "PASS", "warn": "WARN", "fail": "FAIL", "skip": "SKIP"}  # nosec B105


def score_label(score: int) -> str:
    """Human-friendly band for a score: healthy / needs work / critical."""
    if score >= 80:
        return "healthy"
    if score >= 50:
        return "needs work"
    return "critical"


def _escape(cell: str) -> str:
    return cell.replace("|", "\\|").replace("\n", " ")


def _checks_table(result: ScanResult) -> list[str]:
    lines = ["| Status | Check | Category | Detail |", "| --- | --- | --- | --- |"]
    for finding in result.findings:
        label = STATUS_LABEL[finding.status]
        title = _escape(finding.title)
        detail = _escape(finding.detail)
        lines.append(f"| {label} | {title} | {finding.category} | {detail} |")
    return lines


def _breakdown_table(score: ScoreResult) -> list[str]:
    lines = ["| Category | Points lost |", "| --- | --- |"]
    if not score.breakdown:
        lines.append("| - | 0 |")
        return lines
    for category, deduction in score.breakdown.items():
        lines.append(f"| {category} | {deduction} |")
    return lines


def _top_fixes(score: ScoreResult) -> list[str]:
    if not score.top_fixes:
        return ["Nothing to fix - every enabled check passes.", ""]
    lines = []
    for index, (title, suggestion, deduction) in enumerate(score.top_fixes, start=1):
        lines.append(f"{index}. **{title}** (-{deduction}): {suggestion}")
    lines.append("")
    return lines


def render_markdown(result: ScanResult, *, now: datetime | None = None) -> str:
    """Render a ScanResult as the ForgeFix markdown health report."""
    stamp = (now or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    score = result.score
    lines = [
        "# ForgeFix health report",
        "",
        f"- Repository: `{result.root.as_posix()}`",
        f"- Generated: {stamp}",
        f"- ForgeFix version: {__version__}",
        f"- Health score: **{score.total}/100** ({score_label(score.total)})",
        (
            f"- Checks: {score.passed} pass, {score.warned} warn, "
            f"{score.failed} fail, {score.skipped} skip"
        ),
        "",
        "## Checks",
        "",
        *_checks_table(result),
        "",
        "## Category breakdown",
        "",
        *_breakdown_table(score),
        "",
        "## Top fixes",
        "",
        *_top_fixes(score),
    ]
    if result.plugins:
        lines += ["## Plugins", "", ", ".join(f"`{name}`" for name in result.plugins), ""]
    lines += [
        "---",
        "",
        (
            "Generated by ForgeFix, an original MIT-licensed tool. "
            "Only repository metadata was read; no source code was copied from anywhere."
        ),
        "",
    ]
    return "\n".join(lines)


def write_report(path: Path, markdown: str) -> Path:
    """Write ``markdown`` to ``path``, creating parent directories."""
    target = path.expanduser()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(markdown, encoding="utf-8", newline="\n")
    return target
